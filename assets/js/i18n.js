function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  document.documentElement.setAttribute('lang', lang);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    const pairs = el.getAttribute('data-i18n-attr').split(',');
    pairs.forEach(pair => {
      const [attr, key] = pair.split(':').map(s => s.trim());
      if (dict[key] !== undefined) el.setAttribute(attr, dict[key].replace(/&amp;/g,'&').replace(/&mdash;/g,'—').replace(/&larr;/g,'←'));
    });
  });
  document.querySelectorAll('.lang-toggle button').forEach(btn => {
    btn.classList.toggle('on', btn.getAttribute('data-lang') === lang);
  });
  const titleKey = document.body.getAttribute('data-title-key');
  const descKey = document.body.getAttribute('data-desc-key');
  if (titleKey && dict[titleKey]) document.title = dict[titleKey];
  if (descKey && dict[descKey]) {
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute('content', dict[descKey]);
  }
  localStorage.setItem('yachtrelay-lang', lang);
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

// Detects the visitor's language from their browser/OS settings, which is
// what navigator.language actually reflects. There's no reliable client-side
// way to know a visitor is "in Spain" specifically without calling a
// third-party IP-geolocation API on every page load (external dependency,
// added latency, can fail or be blocked). Browser language is instant, has
// no dependency, and gets the right answer for the large majority of real
// visitors, since OS/browser language and physical location correlate
// strongly in practice.
function detectLang() {
  const supported = ['en', 'fr', 'es', 'it'];
  const candidates = (navigator.languages && navigator.languages.length)
    ? navigator.languages
    : [navigator.language || 'en'];
  for (const raw of candidates) {
    const code = raw.slice(0, 2).toLowerCase();
    if (supported.includes(code)) return code;
  }
  return 'en';
}

function initLang() {
  const stored = localStorage.getItem('yachtrelay-lang');
  const initial = stored || detectLang();
  applyLang(initial);
  document.querySelectorAll('.lang-toggle button').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.getAttribute('data-lang')));
  });
}

document.addEventListener('DOMContentLoaded', initLang);
